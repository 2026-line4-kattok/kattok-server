-- 카똑 핵심 도메인 스키마. docs/domain-model.md, docs/conventions.md 기준.

create table users (
	id bigint generated by default as identity primary key,
	email varchar not null unique,
	password_hash varchar not null,
	terms_agreed_at timestamptz not null,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now()
);

create table card_issuers (
	id bigint generated by default as identity primary key,
	name varchar not null,
	code varchar not null unique
);

create table card_products (
	id bigint generated by default as identity primary key,
	issuer_id bigint not null references card_issuers (id),
	name varchar not null,
	card_type varchar not null,
	product_version varchar not null,
	data_status varchar not null,
	source_url varchar,
	annual_fee bigint not null,
	brand varchar,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now()
);

create table card_performance_tiers (
	id bigint generated by default as identity primary key,
	product_id bigint not null references card_products (id),
	level int not null,
	min_amount bigint not null,
	label varchar
);

create table merchant_categories (
	id bigint generated by default as identity primary key,
	name varchar not null,
	code varchar not null unique
);

create table merchants (
	id bigint generated by default as identity primary key,
	name varchar not null,
	channel varchar not null,
	category_id bigint not null references merchant_categories (id)
);

create table merchant_aliases (
	id bigint generated by default as identity primary key,
	merchant_id bigint not null references merchants (id),
	alias varchar not null
);

create table benefit_cap_groups (
	id bigint generated by default as identity primary key,
	product_id bigint not null references card_products (id),
	cap_period varchar not null,
	cap_amount bigint,
	cap_count int,
	description varchar
);

create table benefit_rules (
	id bigint generated by default as identity primary key,
	product_id bigint not null references card_products (id),
	category_id bigint references merchant_categories (id),
	merchant_id bigint references merchants (id),
	required_tier_id bigint references card_performance_tiers (id),
	cap_group_id bigint not null references benefit_cap_groups (id),
	benefit_type varchar not null,
	rate numeric,
	amount bigint,
	point_krw_ratio numeric,
	select_group varchar,
	select_option varchar,
	min_payment_amount bigint,
	max_eligible_txn_amount bigint,
	conditions jsonb,
	source_ref varchar,
	verification_status varchar not null,
	verified_at timestamptz,
	rule_version int not null,
	valid_from date not null,
	valid_to date
);

create table user_cards (
	id bigint generated by default as identity primary key,
	user_id bigint not null references users (id),
	product_id bigint not null references card_products (id),
	created_at timestamptz not null default now(),
	deleted_at timestamptz
);

create table user_card_states (
	id bigint generated by default as identity primary key,
	user_card_id bigint not null references user_cards (id),
	period_month date not null,
	performance_tier_id bigint references card_performance_tiers (id),
	remaining_limit_amount bigint,
	remaining_count int,
	source varchar not null,
	confirmed_at timestamptz not null,
	created_at timestamptz not null default now()
);

create table user_card_benefit_selections (
	id bigint generated by default as identity primary key,
	user_card_id bigint not null references user_cards (id),
	select_group varchar not null,
	selected_option varchar not null,
	effective_from date not null,
	created_at timestamptz not null default now()
);

create table recommendations (
	id bigint generated by default as identity primary key,
	user_id bigint not null references users (id),
	merchant_id bigint not null references merchants (id),
	merchant_name_snapshot varchar not null,
	amount bigint not null,
	payment_method varchar,
	input_snapshot jsonb not null,
	overall_status varchar not null,
	saved_at timestamptz,
	created_at timestamptz not null default now()
);

create table recommendation_items (
	id bigint generated by default as identity primary key,
	recommendation_id bigint not null references recommendations (id),
	user_card_id bigint not null references user_cards (id),
	product_name_snapshot varchar not null,
	issuer_name_snapshot varchar not null,
	status varchar not null,
	is_recommended boolean not null,
	rank_no int,
	expected_benefit_min bigint,
	expected_benefit_max bigint,
	applied_rules jsonb not null,
	unknown_conditions jsonb not null,
	excluded_reasons jsonb not null
);

create table payment_records (
	id bigint generated by default as identity primary key,
	user_id bigint not null references users (id),
	recommendation_id bigint not null unique references recommendations (id),
	status varchar not null,
	confirmed_at timestamptz,
	actual_user_card_id bigint references user_cards (id),
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now()
);
