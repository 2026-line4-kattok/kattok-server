-- V27(결제처 별칭) 다음 배포. PR #33 머지 후 적용한다.
alter table payment_records add column saved_benefit bigint;
alter table payment_records add column actual_card_name_snapshot varchar;
alter table payment_records add column confirmation_version integer not null default 0;

create table card_cap_balances (
 id bigint generated by default as identity primary key,
 user_card_id bigint not null references user_cards(id),
 cap_group_id bigint not null references benefit_cap_groups(id),
 cap_period varchar not null check(cap_period in ('DAILY','MONTHLY','YEARLY')),
 period_start date not null,
 description varchar not null,
 amount_limited boolean not null,
 count_limited boolean not null,
 remaining_amount bigint check(remaining_amount >= 0),
 remaining_count integer check(remaining_count >= 0),
 amount_source varchar not null default 'UNKNOWN',
 count_source varchar not null default 'UNKNOWN',
 base_amount bigint check(base_amount >= 0),
 base_count integer check(base_count >= 0),
 base_amount_source varchar not null default 'UNKNOWN',
 base_count_source varchar not null default 'UNKNOWN',
 amount_revision bigint not null default 0,
 count_revision bigint not null default 0,
 assumed_amount bigint,
 assumed_count integer,
 unique(user_card_id,cap_group_id,cap_period,period_start)
);

create table payment_cap_effects (
 id bigint generated by default as identity primary key,
 payment_record_id bigint not null references payment_records(id),
 balance_id bigint not null references card_cap_balances(id),
 amount_delta bigint not null check(amount_delta >= 0),
 count_delta integer not null check(count_delta >= 0),
 amount_revision bigint not null,
 count_revision bigint not null,
 active boolean not null default true
);
create unique index uq_active_payment_cap_effect on payment_cap_effects(payment_record_id,balance_id) where active;
create index ix_cap_effect_balance on payment_cap_effects(balance_id) where active;
